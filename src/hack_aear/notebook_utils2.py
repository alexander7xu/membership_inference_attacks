def calculate_score_for_prada(
    tested_model, generated_by, calibration_set="imagenet_val", prada_scorer_dict=dict()
):
    lr = 1e-2
    weight_decay = 0.0001
    batch_size = 1000
    epochs = 100
    calibration_size = 250
    calibration_set = "imagenet_val"

    prada_scorer_dict.setdefault(tested_model, {})
    if calibration_set not in prada_scorer_dict[tested_model]:
        # train prada scorer for this tested_model
        belonging_feature_list = load_feature_list(tested_model, tested_model)
        non_belonging_feature_list = load_feature_list(tested_model, calibration_set)
        calibration_belonging, test_belonging = (
            split_feature_list_for_calibration_and_test(
                belonging_feature_list, calibration_size=calibration_size
            )
        )
        calibration_non_belonging, _ = split_feature_list_for_calibration_and_test(
            non_belonging_feature_list, calibration_size=calibration_size
        )
        prada_scorer = train_prada_scorer(
            calibration_belonging,
            calibration_non_belonging,
            lr=lr,
            weight_decay=weight_decay,
            batch_size=batch_size,
            epochs=epochs,
            model_type=tested_model,
        )
        prada_scorer_dict[tested_model][calibration_set] = prada_scorer
    else:
        print(
            f"Using existing Prada scorer for {tested_model} calibrated on {calibration_set}"
        )
        prada_scorer = prada_scorer_dict[tested_model][calibration_set]
    belonging_feature_list = load_feature_list(tested_model, tested_model)
    # non_belonging_feature_list = load_feature_list(tested_model, calibration_set)
    calibration_belonging, test_belonging = split_feature_list_for_calibration_and_test(
        belonging_feature_list, calibration_size=calibration_size
    )
    # calibration_non_belonging, _ = split_feature_list_for_calibration_and_test(non_belonging_feature_list, calibration_size=calibration_size)

    non_belonging_feature_list = load_feature_list(tested_model, generated_by)
    _, test_non_belonging = split_feature_list_for_calibration_and_test(
        non_belonging_feature_list, calibration_size=calibration_size
    )
    belonging_scores = calculate_score_from_feature_list(
        test_belonging,
        score_type="prada",
        prada_scorer=prada_scorer,
        model_type=tested_model,
    )
    non_belonging_scores = calculate_score_from_feature_list(
        test_non_belonging,
        score_type="prada",
        prada_scorer=prada_scorer,
        model_type=tested_model,
    )
    return belonging_scores, non_belonging_scores


def calculate_score_for_prada_multiclass(
    tested_model,
    model_list,
    calibration_set="imagenet_val",
    calibration_size=250,
    lr=1e-2,
    weight_decay=0.0001,
    batch_size=1000,
    epochs=100,
):
    """
    Train a multiclass PRADA scorer on m calibration sets and evaluate on m test sets.

    Args:
        tested_model: The model used to compute features (e.g., "var_16")
        model_list: List of m model names to use as classes (e.g., ["var_16", "var_20", "var_24", "var_30"])
        calibration_set: Name of the calibration set for non-belonging (not used in multiclass)
        calibration_size: Number of samples for calibration per class
        lr, weight_decay, batch_size, epochs: Training hyperparameters

    Returns:
        prada_scorer: Trained multiclass PRADA scorer
        test_sets: List of test feature sets for each class
        class_names: List of class names corresponding to model_list
    """
    calibration_sets = []
    test_sets = []

    # Load calibration and test data for each class
    for model_name in model_list:
        print(f"Loading features for class: {model_name}")
        feature_list = load_feature_list(tested_model, model_name)
        calibration_set_data, test_set_data = (
            split_feature_list_for_calibration_and_test(
                feature_list, calibration_size=calibration_size
            )
        )
        calibration_sets.append(calibration_set_data)
        test_sets.append(test_set_data)

    # Train multiclass scorer
    print(f"\nTraining multiclass PRADA scorer with {len(model_list)} classes...")
    prada_scorer = train_prada_multiclass_scorer(
        calibration_sets,
        lr=lr,
        weight_decay=weight_decay,
        batch_size=batch_size,
        epochs=epochs,
        model_type=tested_model,
    )

    return prada_scorer, test_sets, model_list


def evaluate_prada_multiclass(prada_scorer, test_sets, class_names, model_type="var"):
    """
    Evaluate multiclass PRADA scorer on test sets.

    Args:
        prada_scorer: Trained PradaMulticlass model
        test_sets: List of test feature sets for each class
        class_names: List of class names
        model_type: Model type string

    Returns:
        confusion_matrix: m x m confusion matrix (rows=true, cols=predicted)
        accuracy: Overall accuracy
        per_class_accuracy: Accuracy per class
    """
    num_classes = len(class_names)
    confusion_matrix = np.zeros((num_classes, num_classes))

    prada_scorer.eval()

    with torch.no_grad():
        for true_class_idx, test_set in enumerate(test_sets):
            # Prepare test data
            cond = test_set["conditional"]["log_probs"]
            uncond = test_set["unconditional"]["log_probs"]

            # Convert to tensor format
            if "var" in model_type.lower():
                cond_tensor = tokens_to_token_list_var(
                    torch.from_numpy(np.stack(cond)).cuda()
                )
                uncond_tensor = tokens_to_token_list_var(
                    torch.from_numpy(np.stack(uncond)).cuda()
                )
            elif "infinity" in model_type.lower():
                cond_tensor = tokens_to_token_list_infinity(
                    torch.from_numpy(np.stack(cond)).cuda()
                )
                uncond_tenosr = tokens_to_token_list_infinity(
                    torch.from_numpy(np.stack(uncond)).cuda()
                )
            else:
                cond_tensor = [torch.from_numpy(np.stack(cond)).cuda()]
                uncond_tensor = [torch.from_numpy(np.stack(uncond)).cuda()]

            # Get predictions
            predictions = prada_scorer.predict(cond_tensor, uncond_tensor)
            predictions = predictions.cpu().numpy()

            # Update confusion matrix
            for pred in predictions:
                confusion_matrix[true_class_idx, pred] += 1

    # Normalize to percentages
    row_sums = confusion_matrix.sum(axis=1, keepdims=True)
    confusion_matrix_pct = (confusion_matrix / row_sums) * 100

    # Calculate accuracies
    total_correct = np.trace(confusion_matrix)
    total_samples = confusion_matrix.sum()
    accuracy = total_correct / total_samples

    per_class_accuracy = np.diag(confusion_matrix) / confusion_matrix.sum(axis=1)

    return confusion_matrix_pct, accuracy, per_class_accuracy



def create_attribution_matrix(
    models,
    score_metric="icas",
    use_imagenet_train=False,
    calibration_set="imagenet_val",
):
    """
    Create attribution confusion matrix

    Args:
        models: List of model names (e.g., ['HMAR-d20', 'HMAR-d30', ...])
        score_metric: 'icas' or 'delta'
        use_imagenet_train: If True, use imagenet_train as belonging set
    """
    n_models = len(models)
    confusion_matrix = np.zeros((n_models, n_models))
    std_matrix = np.zeros((n_models, n_models))

    # For each real/true class (row)
    for i, true_model in enumerate(models):
        print(f"Processing true class: {true_model}")

        try:
            # We need to load features computed with each model as the tested_model
            # For each candidate model, we need features computed by that model
            test_scores_dict = {}
            n_samples = None

            # Compute scores against each model (predicted class)
            for j, pred_model in enumerate(models):
                print(f"  Computing scores for {true_model} against {pred_model}")
                if pred_model.lower() == "real":
                    test_scores_dict[pred_model] = np.array([])
                    continue
                # Load test features computed by pred_model on true_model's data

                try:
                    # Compute test scores (how well test samples match this model)
                    if score_metric == "prada":
                        belonging_scores, non_belonging_scores = (
                            calculate_score_for_prada(
                                tested_model=pred_model,
                                generated_by=true_model,
                                calibration_set=calibration_set,
                            )
                        )
                        test_scores = non_belonging_scores
                    else:
                        test_features = load_feature_list(pred_model, true_model)
                        test_scores = calculate_score_from_feature_list(
                            test_features,
                            score_type=score_metric,
                            model_type=pred_model,
                        )

                    test_scores_dict[pred_model] = test_scores

                    if n_samples is None:
                        n_samples = len(test_scores)

                except Exception as e:
                    print(f"    Warning: Could not load features for {pred_model}: {e}")
                    test_scores_dict[pred_model] = np.array([])

            # For each test sample, attribute to model with highest score
            if n_samples is None or n_samples == 0:
                print(f"  No samples found for {true_model}")
                continue

            attributions = []
            real_idx = models.index("Real") if "Real" in models else -1

            for sample_idx in range(n_samples):
                sample_scores = []
                valid_scores = []

                for k, pred_model in enumerate(models):
                    if pred_model.lower() == "real":
                        # Real class placeholder, will be determined by threshold
                        sample_scores.append(-np.inf)
                    elif len(test_scores_dict[pred_model]) > sample_idx:
                        score = test_scores_dict[pred_model][sample_idx]
                        sample_scores.append(score)
                        valid_scores.append(score)
                    else:
                        sample_scores.append(-np.inf)

                # Check if all valid scores are below 0
                # If so, classify as Real; otherwise, take the highest score
                if len(valid_scores) > 0 and all(s < 0 for s in valid_scores):
                    # All scores negative -> classify as Real
                    if real_idx >= 0:
                        predicted_idx = real_idx
                    else:
                        predicted_idx = np.argmax(sample_scores)
                else:
                    # At least one positive score -> attribute to model with highest score
                    predicted_idx = np.argmax(sample_scores)

                attributions.append(predicted_idx)

            # Count attributions for confusion matrix
            attributions = np.array(attributions)
            for j in range(n_models):
                count = np.sum(attributions == j)
                percentage = (count / n_samples) * 100 if n_samples > 0 else 0
                confusion_matrix[i, j] = percentage

                # Calculate std (bootstrap estimate)
                if n_samples > 0:
                    std_matrix[i, j] = np.sqrt(
                        percentage * (100 - percentage) / n_samples
                    )

        except Exception as e:
            print(f"  Error processing {true_model}: {e}")

    return confusion_matrix, std_matrix



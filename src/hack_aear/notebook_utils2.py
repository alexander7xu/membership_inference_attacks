def compute_tpr_at_fpr(belonging_scores, non_belonging_scores, target_fpr=0.01):
    """
    Compute TPR@1%FPR for a specific tested_model vs generated_by combination

    Args:
        belonging_scores: Scores from the model evaluating its own images
        non_belonging_scores: Scores from the model evaluating generated images
        score_metric: 'icas' or 'delta'
        target_fpr: Target false positive rate (default 0.01 for 1%)

    Returns:
        tpr_at_target_fpr, auc, acc, threshold
    """

    # Combine scores and labels
    # Label 0 = non-belonging, Label 1 = belonging
    all_labels = np.concatenate(
        [np.zeros(len(non_belonging_scores)), np.ones(len(belonging_scores))]
    )
    all_scores = np.concatenate([non_belonging_scores, belonging_scores])

    # Compute ROC curve
    fpr, tpr, thresholds = metrics.roc_curve(all_labels, all_scores)
    auc = metrics.auc(fpr, tpr)
    acc = np.max(1 - (fpr + (1 - tpr)) / 2)

    # Find TPR at target FPR
    idx = np.where(fpr <= target_fpr)[0]
    if len(idx) > 0:
        idx = idx[-1]
        tpr_at_target = tpr[idx]
        threshold_at_target = thresholds[idx]
    else:
        tpr_at_target = 0.0
        threshold_at_target = np.inf

    return tpr_at_target, auc, acc, threshold_at_target


